using System.Globalization;
using System.Text;

namespace FunctionalC.Compiler;

/// <summary>
/// Maps Functional C identifiers to C17 identifiers.
/// <list type="bullet">
/// <item>Every source identifier gets a <c>u_</c> prefix (<c>count</c> → <c>u_count</c>, <c>__LINE__</c> → <c>u___LINE__</c>,
///   <c>printf</c> → <c>u_printf</c>, <c>main</c> → <c>u_main</c>). The mapping is injective and never collides with C keywords,
///   preprocessor macros, reserved <c>_*</c> identifiers, or standard library names.</item>
/// <item>Translator-internal helpers, lifted lambdas, and temporaries use the <c>fc_</c> prefix, so they can never collide
///   with any <c>u_</c> source name.</item>
/// </list>
/// </summary>
public static class CNames
{
    public const string Print = "fc_print";
    public const string Add = "fc_add";
    public const string Sub = "fc_sub";
    public const string Mul = "fc_mul";
    public const string Neg = "fc_neg";
    public const string Div = "fc_div";
    public const string Rem = "fc_rem";
    public const string ToChar = "fc_char";
    public const string ToUChar = "fc_uchar";
    public const string TempPrefix = "fc_t";
    public const string FirstFlagPrefix = "fc_first";

    public static string ForSource(string name) => "u_" + name;
}

/// <summary>
/// Emits portable C17 source from a checked Functional C program.
/// Output is deterministic: 4-space indentation, "\n" line endings, and clean enough to compile with
/// <c>-std=c17 -Wall -Wextra -Werror</c>.
///
/// Key translations:
/// <list type="bullet">
/// <item>Types map to fixed-width standard C types: <c>int</c> → <c>int32_t</c>, <c>bool</c> → <c>bool</c>,
///   <c>char</c> → <c>int8_t</c>, <c>unsigned char</c> → <c>uint8_t</c>.</item>
/// <item>Lambdas are lifted to file-scope <c>static inline</c> C functions; captured immutable bindings
///   (including transitive captures of called lambdas) are passed as explicit parameters.</item>
/// <item>Immutable <c>let</c> bindings emit <c>const</c> declarations so the C compiler enforces immutability too.</item>
/// <item>Left-to-right evaluation order is preserved by hoisting earlier effectful operands/arguments into
///   statement-level temporaries (no GNU statement-expression extensions).</item>
/// <item>32-bit signed wraparound and checked division/remainder go through small <c>static inline</c> helpers
///   so the generated C has no signed-overflow or division undefined behavior.</item>
/// </list>
/// </summary>
public sealed class CEmitter
{
    private const string Indent = "    ";

    private readonly StringBuilder _out = new();
    private int _tempCounter;
    private int _loopFlagCounter;

    private sealed record LiftedLambda(
        string CFunctionName,
        LambdaSymbol Symbol,
        LambdaExpr Expr,
        IReadOnlyList<ValueSymbol> Captures);

    private Dictionary<LambdaSymbol, LiftedLambda> _lambdas = new(ReferenceEqualityComparer.Instance);
    private HashSet<ValueSymbol> _readValues = new(ReferenceEqualityComparer.Instance);

    public string Emit(ProgramNode program, string sourceName)
    {
        Line("/*");
        Line($" * Generated by FunctionalC.Compiler from {sourceName}. Do not edit; edit the .fc source and translate again.");
        Line(" */");
        Line("#include <inttypes.h>");
        Line("#include <stdbool.h>");
        Line("#include <stdint.h>");
        Line("#include <stdio.h>");
        Line("#include <stdlib.h>");
        Line("#ifdef _WIN32");
        Line("#include <fcntl.h>");
        Line("#include <io.h>");
        Line("#endif");
        Line();
        Line("/* Runtime support. User identifiers use the 'u_' prefix and internal names use 'fc_',");
        Line(" * so they never collide with each other, C keywords, macros, or standard library names. */");
        Line();
        Line("/* print(int): writes the decimal value and a \"\\n\" newline to standard output. */");
        Line($"static inline void {CNames.Print}(int32_t value)");
        Line("{");
        Line(Indent + "printf(\"%\" PRId32 \"\\n\", value);");
        Line("}");
        Line();
        Line("/* Two's-complement 32-bit wraparound arithmetic without C signed-overflow undefined behavior. */");
        Line($"static inline int32_t {CNames.Add}(int32_t a, int32_t b)");
        Line("{");
        Line(Indent + "return (int32_t)((uint32_t)a + (uint32_t)b);");
        Line("}");
        Line();
        Line($"static inline int32_t {CNames.Sub}(int32_t a, int32_t b)");
        Line("{");
        Line(Indent + "return (int32_t)((uint32_t)a - (uint32_t)b);");
        Line("}");
        Line();
        Line($"static inline int32_t {CNames.Mul}(int32_t a, int32_t b)");
        Line("{");
        Line(Indent + "return (int32_t)((uint32_t)a * (uint32_t)b);");
        Line("}");
        Line();
        Line($"static inline int32_t {CNames.Neg}(int32_t a)");
        Line("{");
        Line(Indent + "return (int32_t)(0u - (uint32_t)a);");
        Line("}");
        Line();
        Line("/* Checked division and remainder: avoids C undefined behavior on /0 and INT32_MIN / -1. */");
        Line($"static inline int32_t {CNames.Div}(int32_t a, int32_t b)");
        Line("{");
        Line(Indent + "if (b == 0) {");
        Line(Indent + Indent + "fprintf(stderr, \"FunctionalC runtime error: division by zero\\n\");");
        Line(Indent + Indent + "exit(1);");
        Line(Indent + "}");
        Line(Indent + "if (a == INT32_MIN && b == -1) {");
        Line(Indent + Indent + "fprintf(stderr, \"FunctionalC runtime error: arithmetic overflow in division\\n\");");
        Line(Indent + Indent + "exit(1);");
        Line(Indent + "}");
        Line(Indent + "return a / b;");
        Line("}");
        Line();
        Line($"static inline int32_t {CNames.Rem}(int32_t a, int32_t b)");
        Line("{");
        Line(Indent + "if (b == 0) {");
        Line(Indent + Indent + "fprintf(stderr, \"FunctionalC runtime error: division by zero\\n\");");
        Line(Indent + Indent + "exit(1);");
        Line(Indent + "}");
        Line(Indent + "if (a == INT32_MIN && b == -1) {");
        Line(Indent + Indent + "fprintf(stderr, \"FunctionalC runtime error: arithmetic overflow in remainder\\n\");");
        Line(Indent + Indent + "exit(1);");
        Line(Indent + "}");
        Line(Indent + "return a % b;");
        Line("}");
        Line();
        Line("/* Narrowing to 8-bit integer types keeps the low 8 bits (two's complement). */");
        Line($"static inline int8_t {CNames.ToChar}(int32_t value)");
        Line("{");
        Line(Indent + "return (int8_t)(uint8_t)(uint32_t)value;");
        Line("}");
        Line();
        Line($"static inline uint8_t {CNames.ToUChar}(int32_t value)");
        Line("{");
        Line(Indent + "return (uint8_t)(uint32_t)value;");
        Line("}");
        Line();
        Line("/* Program */");
        Line();

        FunctionDecl? main = null;
        foreach (var function in program.Functions)
        {
            EmitFunction(function);
            if (function.Name == "main")
            {
                main ??= function;
            }
        }

        if (main is null)
        {
            throw new InvalidOperationException("the checker guarantees an entry point");
        }

        Line("/* C entry point: configures binary stdout on Windows (for \"\\n\" line endings),");
        Line(" * calls the source-level main(), and returns its result as the process exit code. */");
        Line("int main(void)");
        Line("{");
        Line("#ifdef _WIN32");
        Line(Indent + "_setmode(_fileno(stdout), _O_BINARY);");
        Line("#endif");
        Line($"{Indent}return (int){main.Symbol!.CName}();");
        Line("}");
        return _out.ToString();
    }

    private void Line(string text = "") => _out.Append(text).Append('\n');

    private static string TypeName(FcType type) => type switch
    {
        FcType.Int => "int32_t",
        FcType.Bool => "bool",
        FcType.Char => "int8_t",
        FcType.UChar => "uint8_t",
        _ => throw new ArgumentOutOfRangeException(nameof(type)),
    };

    private static string ParameterSignature(IReadOnlyList<Parameter> parameters) =>
        parameters.Count == 0
            ? "void"
            : string.Join(", ", parameters.Select(p => $"{TypeName(p.Type)} {p.Symbol!.CName}"));

    private static string FunctionHeader(FunctionDecl function) =>
        $"{TypeName(function.ReturnType)} {function.Symbol!.CName}({ParameterSignature(function.Parameters)})";

    // ------------------------------------------------------------ lambda lifting & usage analysis

    private void EmitFunction(FunctionDecl function)
    {
        _lambdas = new Dictionary<LambdaSymbol, LiftedLambda>(ReferenceEqualityComparer.Instance);
        _readValues = new HashSet<ValueSymbol>(ReferenceEqualityComparer.Instance);
        _tempCounter = 0;
        _loopFlagCounter = 0;

        var liftedList = new List<LiftedLambda>();
        bool lambdaCallsEnclosing = false;
        CollectLambdas(function, function.Body, liftedList, ref lambdaCallsEnclosing);
        CollectReads(function.Body);

        if (lambdaCallsEnclosing)
        {
            Line(FunctionHeader(function) + ";");
            Line();
        }

        foreach (var lifted in liftedList)
        {
            EmitLiftedLambda(lifted);
        }

        Line(FunctionHeader(function));
        Line("{");
        var bodyLines = new List<string>();
        foreach (var parameter in function.Parameters)
        {
            if (parameter.Symbol is ValueSymbol sym && !_readValues.Contains(sym))
            {
                bodyLines.Add($"(void){sym.CName};");
            }
        }

        EmitStatements(function.Body, bodyLines);
        foreach (var line in bodyLines)
        {
            Line(Indent + line);
        }

        Line("}");
        Line();
    }

    private void CollectLambdas(FunctionDecl enclosing, IReadOnlyList<Stmt> statements, List<LiftedLambda> liftedList, ref bool callsEnclosing)
    {
        foreach (var statement in statements)
        {
            switch (statement)
            {
                case BlockStmt block:
                    CollectLambdas(enclosing, block.Statements, liftedList, ref callsEnclosing);
                    break;
                case IfStmt branch:
                    CollectLambdas(enclosing, Flow.Flatten(branch.Then), liftedList, ref callsEnclosing);
                    if (branch.Else is { } elseStmt)
                    {
                        CollectLambdas(enclosing, Flow.Flatten(elseStmt), liftedList, ref callsEnclosing);
                    }
                    break;
                case WhileStmt loop:
                    CollectLambdas(enclosing, Flow.Flatten(loop.Body), liftedList, ref callsEnclosing);
                    break;
                case DoWhileStmt loop:
                    CollectLambdas(enclosing, Flow.Flatten(loop.Body), liftedList, ref callsEnclosing);
                    break;
                case ForStmt loop:
                    CollectLambdas(enclosing, loop.Init, liftedList, ref callsEnclosing);
                    CollectLambdas(enclosing, Flow.Flatten(loop.Body), liftedList, ref callsEnclosing);
                    break;
                case LetStmt { Initializer: LambdaExpr lambda, Symbol: LambdaSymbol lambdaSymbol } let:
                {
                    var ownParams = new HashSet<ValueSymbol>(
                        lambda.Parameters.Select(p => (ValueSymbol)p.Symbol!),
                        ReferenceEqualityComparer.Instance);
                    var captures = new List<ValueSymbol>();
                    var captureSet = new HashSet<ValueSymbol>(ReferenceEqualityComparer.Instance);
                    ScanLambdaBody(lambda.Body, enclosing.Symbol!, ownParams, captures, captureSet, ref callsEnclosing);

                    string cFuncName = $"fc_lam_{enclosing.Name}_{liftedList.Count + 1}_{let.Name}";
                    var lifted = new LiftedLambda(cFuncName, lambdaSymbol, lambda, captures);
                    _lambdas[lambdaSymbol] = lifted;
                    liftedList.Add(lifted);
                    break;
                }
            }
        }
    }

    private void ScanLambdaBody(
        Expr expr,
        FunctionSymbol enclosing,
        HashSet<ValueSymbol> ownParams,
        List<ValueSymbol> captures,
        HashSet<ValueSymbol> captureSet,
        ref bool callsEnclosing)
    {
        switch (expr)
        {
            case NameExpr { Symbol: ValueSymbol value }:
                if (!ownParams.Contains(value) && captureSet.Add(value))
                {
                    captures.Add(value);
                }
                break;
            case UnaryExpr unary:
                ScanLambdaBody(unary.Operand, enclosing, ownParams, captures, captureSet, ref callsEnclosing);
                break;
            case CastExpr cast:
                ScanLambdaBody(cast.Operand, enclosing, ownParams, captures, captureSet, ref callsEnclosing);
                break;
            case BinaryExpr binary:
                ScanLambdaBody(binary.Left, enclosing, ownParams, captures, captureSet, ref callsEnclosing);
                ScanLambdaBody(binary.Right, enclosing, ownParams, captures, captureSet, ref callsEnclosing);
                break;
            case ConditionalExpr cond:
                ScanLambdaBody(cond.Condition, enclosing, ownParams, captures, captureSet, ref callsEnclosing);
                ScanLambdaBody(cond.WhenTrue, enclosing, ownParams, captures, captureSet, ref callsEnclosing);
                ScanLambdaBody(cond.WhenFalse, enclosing, ownParams, captures, captureSet, ref callsEnclosing);
                break;
            case CallExpr call:
                if (ReferenceEquals(call.Symbol, enclosing))
                {
                    callsEnclosing = true;
                }
                else if (call.Symbol is LambdaSymbol calledLambda && _lambdas.TryGetValue(calledLambda, out var liftedCallee))
                {
                    // Calling a lambda that captures outer variables means this lambda transitively captures them too.
                    foreach (var cap in liftedCallee.Captures)
                    {
                        if (!ownParams.Contains(cap) && captureSet.Add(cap))
                        {
                            captures.Add(cap);
                        }
                    }
                }

                foreach (var arg in call.Arguments)
                {
                    ScanLambdaBody(arg, enclosing, ownParams, captures, captureSet, ref callsEnclosing);
                }
                break;
        }
    }

    private void CollectReads(IReadOnlyList<Stmt> statements)
    {
        foreach (var statement in statements)
        {
            CollectStmtReads(statement);
        }
    }

    private void CollectStmtReads(Stmt statement)
    {
        switch (statement)
        {
            case BlockStmt block:
                CollectReads(block.Statements);
                break;
            case LetStmt { Initializer: LambdaExpr }:
                // Captures are recorded when the lambda is actually called (so an uncalled lambda doesn't hide an unused outer var).
                break;
            case LetStmt let:
                CollectExprReads(let.Initializer);
                break;
            case DeclarationStmt decl:
                foreach (var d in decl.Declarators)
                {
                    CollectExprReads(d.Initializer);
                }
                break;
            case AssignStmt assign:
                if (assign.Op != AssignOp.Set && assign.Symbol is not null)
                {
                    _readValues.Add(assign.Symbol);
                }

                if (assign.Value is not null)
                {
                    CollectExprReads(assign.Value);
                }
                break;
            case ExprStmt exprStmt:
                CollectExprReads(exprStmt.Expression);
                break;
            case ReturnStmt ret:
                CollectExprReads(ret.Value);
                break;
            case IfStmt branch:
                CollectExprReads(branch.Condition);
                CollectStmtReads(branch.Then);
                if (branch.Else is not null)
                {
                    CollectStmtReads(branch.Else);
                }
                break;
            case WhileStmt loop:
                CollectExprReads(loop.Condition);
                CollectStmtReads(loop.Body);
                break;
            case DoWhileStmt loop:
                CollectStmtReads(loop.Body);
                CollectExprReads(loop.Condition);
                break;
            case ForStmt loop:
                CollectReads(loop.Init);
                if (loop.Condition is not null)
                {
                    CollectExprReads(loop.Condition);
                }

                CollectStmtReads(loop.Body);
                CollectReads(loop.Update);
                break;
        }
    }

    private void CollectExprReads(Expr expr)
    {
        switch (expr)
        {
            case NameExpr { Symbol: ValueSymbol value }:
                _readValues.Add(value);
                break;
            case UnaryExpr unary:
                CollectExprReads(unary.Operand);
                break;
            case CastExpr cast:
                CollectExprReads(cast.Operand);
                break;
            case BinaryExpr binary:
                CollectExprReads(binary.Left);
                CollectExprReads(binary.Right);
                break;
            case ConditionalExpr cond:
                CollectExprReads(cond.Condition);
                CollectExprReads(cond.WhenTrue);
                CollectExprReads(cond.WhenFalse);
                break;
            case CallExpr call:
                if (call.Symbol is LambdaSymbol lambdaSym && _lambdas.TryGetValue(lambdaSym, out var lifted))
                {
                    foreach (var cap in lifted.Captures)
                    {
                        _readValues.Add(cap);
                    }
                }

                foreach (var arg in call.Arguments)
                {
                    CollectExprReads(arg);
                }
                break;
        }
    }

    private void EmitLiftedLambda(LiftedLambda lifted)
    {
        var allParams = new List<string>();
        foreach (var cap in lifted.Captures)
        {
            allParams.Add($"const {TypeName(cap.Type!.Value)} {cap.CName}");
        }

        foreach (var p in lifted.Expr.Parameters)
        {
            allParams.Add($"const {TypeName(p.Type)} {p.Symbol!.CName}");
        }

        string paramList = allParams.Count == 0 ? "void" : string.Join(", ", allParams);
        Line($"static inline {TypeName(lifted.Symbol.ReturnType!.Value)} {lifted.CFunctionName}({paramList})");
        Line("{");

        var lambdaReads = new HashSet<ValueSymbol>(ReferenceEqualityComparer.Instance);
        CollectLambdaLocalReads(lifted.Expr.Body, lambdaReads);

        var bodyLines = new List<string>();
        foreach (var p in lifted.Expr.Parameters)
        {
            if (p.Symbol is ValueSymbol sym && !lambdaReads.Contains(sym))
            {
                bodyLines.Add($"(void){sym.CName};");
            }
        }

        string value = EmitExpr(lifted.Expr.Body, bodyLines);
        bodyLines.Add($"return {value};");
        foreach (var line in bodyLines)
        {
            Line(Indent + line);
        }

        Line("}");
        Line();
    }

    private void CollectLambdaLocalReads(Expr expr, HashSet<ValueSymbol> reads)
    {
        switch (expr)
        {
            case NameExpr { Symbol: ValueSymbol v }:
                reads.Add(v);
                break;
            case UnaryExpr u:
                CollectLambdaLocalReads(u.Operand, reads);
                break;
            case CastExpr c:
                CollectLambdaLocalReads(c.Operand, reads);
                break;
            case BinaryExpr b:
                CollectLambdaLocalReads(b.Left, reads);
                CollectLambdaLocalReads(b.Right, reads);
                break;
            case ConditionalExpr cond:
                CollectLambdaLocalReads(cond.Condition, reads);
                CollectLambdaLocalReads(cond.WhenTrue, reads);
                CollectLambdaLocalReads(cond.WhenFalse, reads);
                break;
            case CallExpr call:
                foreach (var arg in call.Arguments)
                {
                    CollectLambdaLocalReads(arg, reads);
                }
                break;
        }
    }

    // ------------------------------------------------------------ statements

    private static IEnumerable<string> Indented(IEnumerable<string> lines) => lines.Select(l => Indent + l);

    private void EmitStatements(IReadOnlyList<Stmt> statements, List<string> lines)
    {
        foreach (var statement in statements)
        {
            EmitStatement(statement, lines);
        }
    }

    private void EmitStatement(Stmt statement, List<string> lines)
    {
        switch (statement)
        {
            case EmptyStmt:
                break;

            case BlockStmt block:
                lines.Add("{");
                var inner = new List<string>();
                EmitStatements(block.Statements, inner);
                lines.AddRange(Indented(inner));
                lines.Add("}");
                break;

            case LetStmt { Initializer: LambdaExpr }:
                // Lifted to a file-scope static inline function; nothing to emit at the binding site.
                break;

            case LetStmt let:
            {
                var sym = (ValueSymbol)let.Symbol!;
                string init = EmitExpr(let.Initializer, lines);
                lines.Add($"const {TypeName(sym.Type!.Value)} {sym.CName} = {init};");
                if (!_readValues.Contains(sym))
                {
                    lines.Add($"(void){sym.CName};");
                }
                break;
            }

            case DeclarationStmt declaration:
            {
                string type = TypeName(declaration.Type);
                foreach (var declarator in declaration.Declarators)
                {
                    var sym = declarator.Symbol!;
                    string init = EmitExpr(declarator.Initializer, lines);
                    lines.Add($"{type} {sym.CName} = {init};");
                    if (!_readValues.Contains(sym))
                    {
                        lines.Add($"(void){sym.CName};");
                    }
                }
                break;
            }

            case AssignStmt assign:
                lines.Add(EmitAssignment(assign, lines) + ";");
                break;

            case ExprStmt { Expression: CallExpr { IsPrint: true } print }:
            {
                string arg = EmitExpr(print.Arguments[0], lines);
                lines.Add($"{CNames.Print}({arg});");
                break;
            }

            case ExprStmt { Expression: CallExpr call }:
            {
                string callText = EmitCall(call, lines);
                lines.Add($"(void){callText};");
                break;
            }

            case ReturnStmt ret:
            {
                string val = EmitExpr(ret.Value, lines);
                lines.Add($"return {val};");
                break;
            }

            case BreakStmt:
                lines.Add("break;");
                break;

            case ContinueStmt:
                lines.Add("continue;");
                break;

            case IfStmt branch:
                EmitIf(branch, lines);
                break;

            case WhileStmt loop:
                EmitWhile(loop, lines);
                break;

            case DoWhileStmt loop:
                EmitDoWhile(loop, lines);
                break;

            case ForStmt loop:
                EmitFor(loop, lines);
                break;

            default:
                throw new InvalidOperationException($"statement {statement.GetType().Name} cannot be emitted here");
        }
    }

    private string EmitAssignment(AssignStmt assign, List<string> prep)
    {
        string name = assign.Symbol!.CName;
        if (assign.Op == AssignOp.Set)
        {
            return $"{name} = {EmitExpr(assign.Value!, prep)}";
        }

        string helper = assign.Op switch
        {
            AssignOp.Increment or AssignOp.Add => CNames.Add,
            AssignOp.Decrement or AssignOp.Subtract => CNames.Sub,
            AssignOp.Multiply => CNames.Mul,
            AssignOp.Divide => CNames.Div,
            AssignOp.Remainder => CNames.Rem,
            _ => throw new InvalidOperationException($"unexpected assignment operator {assign.Op}"),
        };

        string operand = assign.Value is { } value ? EmitExpr(value, prep) : "1";
        return assign.Symbol.Type switch
        {
            FcType.Char => $"{name} = {CNames.ToChar}({helper}((int32_t){name}, {operand}))",
            FcType.UChar => $"{name} = {CNames.ToUChar}({helper}((int32_t){name}, {operand}))",
            _ => $"{name} = {helper}({name}, {operand})",
        };
    }

    private void EmitIf(IfStmt branch, List<string> lines)
    {
        string cond = EmitCondition(branch.Condition, lines);
        lines.Add($"if ({cond}) {{");
        var thenLines = new List<string>();
        EmitStatements(Flow.Flatten(branch.Then), thenLines);
        lines.AddRange(Indented(thenLines));

        if (branch.Else is IfStmt elseIf)
        {
            // Only chain "} else if (...)" when the nested condition needs no prep statements.
            var elseIfPrep = new List<string>();
            string nestedCond = EmitCondition(elseIf.Condition, elseIfPrep);
            if (elseIfPrep.Count == 0)
            {
                lines.Add($"}} else if ({nestedCond}) {{");
                EmitIfTail(elseIf, lines);
                return;
            }

            lines.Add("} else {");
            var nestedLines = new List<string>();
            EmitIf(elseIf, nestedLines);
            lines.AddRange(Indented(nestedLines));
            lines.Add("}");
            return;
        }

        if (branch.Else is { } other)
        {
            lines.Add("} else {");
            var elseLines = new List<string>();
            EmitStatements(Flow.Flatten(other), elseLines);
            lines.AddRange(Indented(elseLines));
            lines.Add("}");
        }
        else
        {
            lines.Add("}");
        }
    }

    private void EmitIfTail(IfStmt branch, List<string> lines)
    {
        var thenLines = new List<string>();
        EmitStatements(Flow.Flatten(branch.Then), thenLines);
        lines.AddRange(Indented(thenLines));

        if (branch.Else is IfStmt elseIf)
        {
            var elseIfPrep = new List<string>();
            string nestedCond = EmitCondition(elseIf.Condition, elseIfPrep);
            if (elseIfPrep.Count == 0)
            {
                lines.Add($"}} else if ({nestedCond}) {{");
                EmitIfTail(elseIf, lines);
                return;
            }

            lines.Add("} else {");
            var nestedLines = new List<string>();
            EmitIf(elseIf, nestedLines);
            lines.AddRange(Indented(nestedLines));
            lines.Add("}");
        }
        else if (branch.Else is { } other)
        {
            lines.Add("} else {");
            var elseLines = new List<string>();
            EmitStatements(Flow.Flatten(other), elseLines);
            lines.AddRange(Indented(elseLines));
            lines.Add("}");
        }
        else
        {
            lines.Add("}");
        }
    }

    private void EmitWhile(WhileStmt loop, List<string> lines)
    {
        var condPrep = new List<string>();
        string cond = EmitCondition(loop.Condition, condPrep);
        var bodyLines = new List<string>();
        EmitStatements(Flow.Flatten(loop.Body), bodyLines);

        if (condPrep.Count == 0)
        {
            lines.Add($"while ({cond}) {{");
            lines.AddRange(Indented(bodyLines));
            lines.Add("}");
        }
        else
        {
            lines.Add("while (true) {");
            var combined = new List<string>();
            combined.AddRange(condPrep);
            combined.Add($"if (!({cond})) {{");
            combined.Add(Indent + "break;");
            combined.Add("}");
            combined.AddRange(bodyLines);
            lines.AddRange(Indented(combined));
            lines.Add("}");
        }
    }

    private void EmitDoWhile(DoWhileStmt loop, List<string> lines)
    {
        var condPrep = new List<string>();
        string cond = EmitCondition(loop.Condition, condPrep);
        var bodyLines = new List<string>();
        EmitStatements(Flow.Flatten(loop.Body), bodyLines);

        if (condPrep.Count == 0)
        {
            lines.Add("do {");
            lines.AddRange(Indented(bodyLines));
            lines.Add($"}} while ({cond});");
        }
        else
        {
            // A 'for' header flag keeps native 'break' and 'continue' exact when the condition needs prep statements.
            string flag = CNames.FirstFlagPrefix + (++_loopFlagCounter).ToString(CultureInfo.InvariantCulture);
            lines.Add($"for (bool {flag} = true; ; {flag} = false) {{");
            var combined = new List<string> { $"if (!{flag}) {{" };
            combined.AddRange(Indented(condPrep));
            combined.Add(Indent + $"if (!({cond})) {{");
            combined.Add(Indent + Indent + "break;");
            combined.Add(Indent + "}");
            combined.Add("}");
            combined.AddRange(bodyLines);
            lines.AddRange(Indented(combined));
            lines.Add("}");
        }
    }

    private void EmitFor(ForStmt loop, List<string> lines)
    {
        // Try emitting a native C 'for (init; cond; update)' when every part fits cleanly without prep statements.
        var condPrep = new List<string>();
        string condText = loop.Condition is null ? "" : EmitCondition(loop.Condition, condPrep);

        if (condPrep.Count == 0
            && TryFormatSimpleForInit(loop.Init, out string initText)
            && TryFormatSimpleForUpdate(loop.Update, out string updateText))
        {
            string header = (initText, condText, updateText) switch
            {
                ("", "", "") => "for (;;)",
                _ => $"for ({initText}; {condText}; {updateText})",
            };
            lines.Add(header + " {");
            var bodyLines = new List<string>();
            EmitStatements(Flow.Flatten(loop.Body), bodyLines);
            lines.AddRange(Indented(bodyLines));
            lines.Add("}");
            return;
        }

        // General form: keeps loop-header declarations scoped, runs update on 'continue', and evaluates cond with prep.
        lines.Add("{");
        var blockLines = new List<string>();
        EmitStatements(loop.Init, blockLines);
        var body = new List<string>();
        EmitStatements(Flow.Flatten(loop.Body), body);

        if (loop.Update.Count > 0)
        {
            string flag = CNames.FirstFlagPrefix + (++_loopFlagCounter).ToString(CultureInfo.InvariantCulture);
            blockLines.Add($"for (bool {flag} = true; ; {flag} = false) {{");
            var inner = new List<string> { $"if (!{flag}) {{" };
            var updateLines = new List<string>();
            EmitStatements(loop.Update, updateLines);
            inner.AddRange(Indented(updateLines));
            inner.Add("}");
            if (loop.Condition is not null)
            {
                inner.AddRange(condPrep);
                inner.Add($"if (!({condText})) {{");
                inner.Add(Indent + "break;");
                inner.Add("}");
            }

            inner.AddRange(body);
            blockLines.AddRange(Indented(inner));
            blockLines.Add("}");
        }
        else if (condPrep.Count == 0)
        {
            blockLines.Add(loop.Condition is null ? "for (;;) {" : $"while ({condText}) {{");
            blockLines.AddRange(Indented(body));
            blockLines.Add("}");
        }
        else
        {
            blockLines.Add("while (true) {");
            var inner = new List<string>();
            inner.AddRange(condPrep);
            inner.Add($"if (!({condText})) {{");
            inner.Add(Indent + "break;");
            inner.Add("}");
            inner.AddRange(body);
            blockLines.AddRange(Indented(inner));
            blockLines.Add("}");
        }

        lines.AddRange(Indented(blockLines));
        lines.Add("}");
    }

    private bool TryFormatSimpleForInit(IReadOnlyList<Stmt> init, out string text)
    {
        if (init.Count == 0)
        {
            text = "";
            return true;
        }

        if (init.Count == 1 && init[0] is DeclarationStmt decl)
        {
            if (decl.Declarators.Any(d => !_readValues.Contains(d.Symbol!)))
            {
                text = "";
                return false;
            }

            var prep = new List<string>();
            var parts = new List<string>();
            foreach (var d in decl.Declarators)
            {
                parts.Add($"{d.Symbol!.CName} = {EmitExpr(d.Initializer, prep)}");
            }

            if (prep.Count > 0)
            {
                text = "";
                return false;
            }

            text = $"{TypeName(decl.Type)} {string.Join(", ", parts)}";
            return true;
        }

        if (init.Count == 1 && init[0] is LetStmt { Initializer: not LambdaExpr } let)
        {
            var sym = (ValueSymbol)let.Symbol!;
            if (!_readValues.Contains(sym))
            {
                text = "";
                return false;
            }

            var prep = new List<string>();
            string expr = EmitExpr(let.Initializer, prep);
            if (prep.Count > 0)
            {
                text = "";
                return false;
            }

            text = $"const {TypeName(sym.Type!.Value)} {sym.CName} = {expr}";
            return true;
        }

        // Comma-separated simple statements (assignments / calls).
        return TryFormatSimpleExprList(init, out text);
    }

    private bool TryFormatSimpleForUpdate(IReadOnlyList<Stmt> update, out string text)
    {
        if (update.Count == 0)
        {
            text = "";
            return true;
        }

        return TryFormatSimpleExprList(update, out text);
    }

    private bool TryFormatSimpleExprList(IReadOnlyList<Stmt> statements, out string text)
    {
        var prep = new List<string>();
        var parts = new List<string>();
        foreach (var stmt in statements)
        {
            switch (stmt)
            {
                case AssignStmt assign:
                    parts.Add(EmitAssignment(assign, prep));
                    break;
                case ExprStmt { Expression: CallExpr { IsPrint: true } print }:
                    parts.Add($"{CNames.Print}({EmitExpr(print.Arguments[0], prep)})");
                    break;
                case ExprStmt { Expression: CallExpr call }:
                    parts.Add($"(void){EmitCall(call, prep)}");
                    break;
                default:
                    text = "";
                    return false;
            }
        }

        if (prep.Count > 0)
        {
            text = "";
            return false;
        }

        text = string.Join(", ", parts);
        return true;
    }

    // ------------------------------------------------------------ expressions

    private string NewTemp() => CNames.TempPrefix + (++_tempCounter).ToString(CultureInfo.InvariantCulture);

    private string EmitExpr(Expr expression, List<string> prep) =>
        expression.ConvertTo is { } target ? EmitConverted(expression, target, prep) : EmitUnconverted(expression, prep);

    private string EmitCondition(Expr condition, List<string> prep) =>
        EmitConverted(condition, FcType.Bool, prep);

    private static string IntLiteral(long value) =>
        value == int.MinValue ? "INT32_MIN" : value.ToString(CultureInfo.InvariantCulture);

    private string EmitConverted(Expr expression, FcType target, List<string> prep)
    {
        if (expression.Type is not { } source || source == target)
        {
            return EmitUnconverted(expression, prep);
        }

        switch (expression)
        {
            case IntLiteralExpr number:
                return target switch
                {
                    FcType.Bool => number.Value != 0 ? "true" : "false",
                    FcType.Char => $"((int8_t){unchecked((sbyte)number.Value).ToString(CultureInfo.InvariantCulture)})",
                    FcType.UChar => $"((uint8_t){unchecked((byte)number.Value).ToString(CultureInfo.InvariantCulture)})",
                    _ => IntLiteral(number.Value),
                };
            case BoolLiteralExpr boolean:
                return target switch
                {
                    FcType.Int => boolean.Value ? "1" : "0",
                    FcType.Char => boolean.Value ? "((int8_t)1)" : "((int8_t)0)",
                    FcType.UChar => boolean.Value ? "((uint8_t)1)" : "((uint8_t)0)",
                    _ => boolean.Value ? "true" : "false",
                };
        }

        string code = EmitUnconverted(expression, prep);
        return (source, target) switch
        {
            (FcType.Bool, FcType.Int) => $"((int32_t)({code}))",
            (FcType.Bool, FcType.Char) => $"((int8_t)({code}))",
            (FcType.Bool, FcType.UChar) => $"((uint8_t)({code}))",
            (FcType.Int or FcType.Char or FcType.UChar, FcType.Bool) => $"({code} != 0)",
            (FcType.Char or FcType.UChar, FcType.Int) => $"((int32_t)({code}))",
            (FcType.Int, FcType.Char) => $"{CNames.ToChar}({code})",
            (FcType.UChar, FcType.Char) => $"{CNames.ToChar}((int32_t)({code}))",
            (FcType.Int, FcType.UChar) => $"{CNames.ToUChar}({code})",
            (FcType.Char, FcType.UChar) => $"{CNames.ToUChar}((int32_t)({code}))",
            _ => code,
        };
    }

    private string EmitUnconverted(Expr expression, List<string> prep) => expression switch
    {
        IntLiteralExpr literal => IntLiteral(literal.Value),
        BoolLiteralExpr boolean => boolean.Value ? "true" : "false",
        NameExpr name => name.Symbol!.CName,
        UnaryExpr { Op: UnaryOp.Negate } unary => $"{CNames.Neg}({EmitExpr(unary.Operand, prep)})",
        UnaryExpr { Op: UnaryOp.Not, Operand.Type: FcType.Bool } unary => $"(!({EmitExpr(unary.Operand, prep)}))",
        UnaryExpr { Op: UnaryOp.Not } unary => $"({EmitExpr(unary.Operand, prep)} == 0)",
        CastExpr cast => EmitExpr(cast.Operand, prep), // the checker recorded the conversion on the operand
        BinaryExpr binary => EmitBinary(binary, prep),
        ConditionalExpr conditional => EmitConditional(conditional, prep),
        CallExpr call => EmitCall(call, prep),
        _ => throw new InvalidOperationException($"unexpected expression node {expression.GetType().Name}"),
    };

    private string EmitConditional(ConditionalExpr conditional, List<string> prep)
    {
        string cond = EmitCondition(conditional.Condition, prep);
        var truePrep = new List<string>();
        string whenTrue = EmitExpr(conditional.WhenTrue, truePrep);
        var falsePrep = new List<string>();
        string whenFalse = EmitExpr(conditional.WhenFalse, falsePrep);

        if (truePrep.Count == 0 && falsePrep.Count == 0)
        {
            return $"({cond} ? {whenTrue} : {whenFalse})";
        }

        string temp = NewTemp();
        prep.Add($"{TypeName(conditional.Type!.Value)} {temp};");
        prep.Add($"if ({cond}) {{");
        prep.AddRange(Indented(truePrep));
        prep.Add($"{Indent}{temp} = {whenTrue};");
        prep.Add("} else {");
        prep.AddRange(Indented(falsePrep));
        prep.Add($"{Indent}{temp} = {whenFalse};");
        prep.Add("}");
        return temp;
    }

    private string EmitBinary(BinaryExpr binary, List<string> prep)
    {
        if (binary.Op is BinaryOp.And or BinaryOp.Or)
        {
            string leftCond = EmitCondition(binary.Left, prep);
            var rightPrep = new List<string>();
            string rightCond = EmitCondition(binary.Right, rightPrep);
            if (rightPrep.Count == 0)
            {
                return $"({leftCond} {binary.Op.Source()} {rightCond})";
            }

            string temp = NewTemp();
            if (binary.Op == BinaryOp.And)
            {
                prep.Add($"bool {temp} = false;");
                prep.Add($"if ({leftCond}) {{");
                prep.AddRange(Indented(rightPrep));
                prep.Add($"{Indent}{temp} = {rightCond};");
                prep.Add("}");
            }
            else
            {
                prep.Add($"bool {temp} = true;");
                prep.Add($"if (!({leftCond})) {{");
                prep.AddRange(Indented(rightPrep));
                prep.Add($"{Indent}{temp} = {rightCond};");
                prep.Add("}");
            }

            return temp;
        }

        // Standard C leaves binary operand evaluation order unspecified, so bind the left operand first
        // whenever both operands may have effects.
        bool sequence = MayHaveEffects(binary.Left) && MayHaveEffects(binary.Right);
        string left = EmitExpr(binary.Left, prep);
        if (sequence)
        {
            FcType leftType = binary.Left.ConvertTo ?? binary.Left.Type!.Value;
            string temp = NewTemp();
            prep.Add($"{TypeName(leftType)} {temp} = {left};");
            left = temp;
        }

        string right = EmitExpr(binary.Right, prep);
        return binary.Op switch
        {
            BinaryOp.Add => $"{CNames.Add}({left}, {right})",
            BinaryOp.Subtract => $"{CNames.Sub}({left}, {right})",
            BinaryOp.Multiply => $"{CNames.Mul}({left}, {right})",
            BinaryOp.Divide => $"{CNames.Div}({left}, {right})",
            BinaryOp.Remainder => $"{CNames.Rem}({left}, {right})",
            _ => $"({left} {binary.Op.Source()} {right})",
        };
    }

    private string EmitCall(CallExpr call, List<string> prep)
    {
        string callee;
        var args = new List<string>();
        if (call.Symbol is LambdaSymbol lambdaSym)
        {
            var lifted = _lambdas[lambdaSym];
            callee = lifted.CFunctionName;
            foreach (var cap in lifted.Captures)
            {
                args.Add(cap.CName);
            }
        }
        else
        {
            callee = call.Symbol!.CName;
        }

        // Standard C leaves argument evaluation order unspecified; bind earlier effectful arguments
        // to temporaries in source order when two or more arguments may have effects.
        int lastEffectIndex = -1;
        int effectCount = 0;
        for (int i = 0; i < call.Arguments.Count; i++)
        {
            if (MayHaveEffects(call.Arguments[i]))
            {
                effectCount++;
                lastEffectIndex = i;
            }
        }

        bool needTemps = effectCount >= 2;
        for (int i = 0; i < call.Arguments.Count; i++)
        {
            var arg = call.Arguments[i];
            string argText = EmitExpr(arg, prep);
            if (needTemps && i < lastEffectIndex && !IsAtom(arg))
            {
                FcType argType = arg.ConvertTo ?? arg.Type!.Value;
                string temp = NewTemp();
                prep.Add($"{TypeName(argType)} {temp} = {argText};");
                args.Add(temp);
            }
            else
            {
                args.Add(argText);
            }
        }

        return $"{callee}({string.Join(", ", args)})";
    }

    private static bool IsAtom(Expr expression) => expression is IntLiteralExpr or BoolLiteralExpr or NameExpr;

    private static bool MayHaveEffects(Expr expression) => expression switch
    {
        CallExpr => true,
        BinaryExpr { Op: BinaryOp.Divide or BinaryOp.Remainder } => true,
        BinaryExpr binary => MayHaveEffects(binary.Left) || MayHaveEffects(binary.Right),
        UnaryExpr unary => MayHaveEffects(unary.Operand),
        CastExpr cast => MayHaveEffects(cast.Operand),
        ConditionalExpr conditional => MayHaveEffects(conditional.Condition)
                                       || MayHaveEffects(conditional.WhenTrue)
                                       || MayHaveEffects(conditional.WhenFalse),
        _ => false,
    };
}
