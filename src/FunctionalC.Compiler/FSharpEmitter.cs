using System.Globalization;
using System.Text;

namespace FunctionalC.Compiler;

/// <summary>
/// Maps Functional C identifiers to F# identifiers.
/// <list type="bullet">
/// <item>F# keywords and reserved words are quoted: <c>match</c> → <c>``match``</c>.</item>
/// <item>Names starting with an uppercase letter or '_' get a <c>u'</c> prefix (<c>None</c> → <c>u'None</c>) so that
///   F# never reads them as union cases or active patterns (None, Some, Ok, Failure, ...) or special
///   identifiers such as <c>__LINE__</c>.</item>
/// <item>Translator-internal names use the <c>fc'</c> prefix. Functional C identifiers cannot contain an
///   apostrophe, so neither prefix can collide with a source name.</item>
/// </list>
/// </summary>
public static class FSharpNames
{
    public const string Print = "fc'print";
    public const string Ignore = "fc'ignore";
    public const string Not = "fc'not";
    public const string EntryPoint = "fc'entry";
    public const string TempPrefix = "fc't";

    /// <summary>F# keywords, reserved-for-future words, and OCaml-compatibility keywords.</summary>
    public static readonly IReadOnlySet<string> Keywords = new HashSet<string>(StringComparer.Ordinal)
    {
        "abstract", "and", "as", "assert", "base", "begin", "class", "default", "delegate", "do", "done",
        "downcast", "downto", "elif", "else", "end", "exception", "extern", "false", "finally", "fixed",
        "for", "fun", "function", "global", "if", "in", "inherit", "inline", "interface", "internal", "lazy",
        "let", "match", "member", "module", "mutable", "namespace", "new", "not", "null", "of", "open", "or",
        "override", "private", "public", "rec", "return", "select", "sig", "static", "struct", "then", "to",
        "true", "try", "type", "upcast", "use", "val", "void", "when", "while", "with", "yield", "const",
        "asr", "land", "lor", "lsl", "lsr", "lxor", "mod",
        "atomic", "break", "checked", "component", "constraint", "constructor", "continue", "eager",
        "event", "external", "functor", "include", "measure", "method", "mixin", "object", "parallel",
        "params", "process", "protected", "pure", "recursive", "sealed", "tailcall", "trait", "virtual",
        "volatile",
    };

    public static string ForSource(string name)
    {
        if (Keywords.Contains(name))
        {
            return "``" + name + "``";
        }

        if (char.IsAsciiLetterUpper(name[0]) || name[0] == '_')
        {
            return "u'" + name;
        }

        return name;
    }
}

/// <summary>
/// Emits F# source from a checked program. Output is deterministic: 4-space indentation, "\n" line endings,
/// and every compound expression fully parenthesized. Calls are curried: <c>f (x: int) (y: int)</c>, <c>f a b</c>,
/// and zero-parameter functions/lambdas take <c>()</c>.
/// </summary>
public sealed class FSharpEmitter
{
    private const string Indent = "    ";

    private readonly StringBuilder _out = new();
    private int _tempCounter;

    public string Emit(ProgramNode program, string sourceName)
    {
        Line($"// <auto-generated>");
        Line($"// Generated by FunctionalC.Compiler from {sourceName}. Do not edit; edit the .fc source and translate again.");
        Line($"// </auto-generated>");
        Line("module FunctionalCProgram");
        Line();
        Line("// Runtime support. Internal names contain an apostrophe, which Functional C identifiers cannot,");
        Line("// so they never collide with names from the source program.");
        Line();
        Line("/// print(int): writes the decimal value (invariant culture) and a \"\\n\" newline to standard output.");
        Line($"let {FSharpNames.Print} (value: int) : unit =");
        Line(Indent + "System.Console.Out.Write(value.ToString(System.Globalization.CultureInfo.InvariantCulture))");
        Line(Indent + "System.Console.Out.Write('\\n')");
        Line();
        Line("/// Discards the result of a call used as a statement (the call itself has already run).");
        Line($"let inline {FSharpNames.Ignore} (_value: 'T) : unit = ()");
        Line();
        Line("/// Logical negation for the '!' operator.");
        Line($"let inline {FSharpNames.Not} (value: bool) : bool = not value");
        Line();
        Line("// Program");
        Line();

        FunctionDecl? main = null;
        foreach (var function in program.Functions)
        {
            EmitFunction(function);
            if (function.Name == "main")
            {
                main ??= function;
            }
        }

        if (main is null)
        {
            throw new InvalidOperationException("the checker guarantees an entry point");
        }

        Line("// .NET entry point: calls the source-level main() and returns its result as the exit code.");
        Line("[<EntryPoint>]");
        Line($"let {FSharpNames.EntryPoint} (_args: string array) : int =");
        Line($"{Indent}{main.Symbol!.FSharpName} ()");
        return _out.ToString();
    }

    private void Line(string text = "") => _out.Append(text).Append('\n');

    private static string TypeName(FcType type) => type == FcType.Int ? "int" : "bool";

    private void EmitFunction(FunctionDecl function)
    {
        var header = new StringBuilder("let ");
        if (function.Symbol!.IsRecursive)
        {
            header.Append("rec ");
        }

        header.Append(function.Symbol.FSharpName);
        header.Append(ParameterList(function.Parameters));
        header.Append($" : {TypeName(function.ReturnType)} =");
        Line(header.ToString());

        foreach (var statement in function.Body)
        {
            Line(Indent + EmitStatement(statement));
        }

        Line();
    }

    private static string ParameterList(IReadOnlyList<Parameter> parameters) =>
        parameters.Count == 0
            ? " ()"
            : string.Concat(parameters.Select(p => $" ({p.Symbol!.FSharpName}: {TypeName(p.Type)})"));

    private string EmitStatement(Stmt statement) => statement switch
    {
        LetStmt let => $"let {let.Symbol!.FSharpName} = {EmitExpression(let.Initializer)}",
        ExprStmt { Expression: CallExpr { IsPrint: true } print } => $"{FSharpNames.Print} {EmitExpression(print.Arguments[0])}",
        ExprStmt { Expression: CallExpr call } => $"{FSharpNames.Ignore} {EmitCall(call)}",
        ReturnStmt ret => EmitExpression(ret.Value),
        _ => throw new InvalidOperationException($"statement {statement.GetType().Name} cannot be emitted (the checker should have rejected it)"),
    };

    /// <summary>Returns either an atom (name, non-negative literal, true/false) or a fully parenthesized expression.</summary>
    private string EmitExpression(Expr expression) => expression switch
    {
        IntLiteralExpr literal => literal.Value >= 0
            ? literal.Value.ToString(CultureInfo.InvariantCulture)
            : $"({literal.Value.ToString(CultureInfo.InvariantCulture)})",
        BoolLiteralExpr boolean => boolean.Value ? "true" : "false",
        NameExpr name => name.Symbol!.FSharpName,
        UnaryExpr { Op: UnaryOp.Negate } unary => $"(-{EmitExpression(unary.Operand)})",
        UnaryExpr { Op: UnaryOp.Not } unary => $"({FSharpNames.Not} {EmitExpression(unary.Operand)})",
        BinaryExpr binary => EmitBinary(binary),
        ConditionalExpr conditional =>
            $"(if {EmitExpression(conditional.Condition)} then {EmitExpression(conditional.WhenTrue)} else {EmitExpression(conditional.WhenFalse)})",
        CallExpr call => EmitCall(call),
        LambdaExpr lambda => $"(fun{ParameterList(lambda.Parameters)} -> {EmitExpression(lambda.Body)})",
        _ => throw new InvalidOperationException($"unexpected expression node {expression.GetType().Name}"),
    };

    private string NewTemp() => FSharpNames.TempPrefix + (++_tempCounter).ToString(CultureInfo.InvariantCulture);

    private static string FSharpOperator(BinaryOp op) => op switch
    {
        BinaryOp.Equal => "=",
        BinaryOp.NotEqual => "<>",
        _ => op.Source(), // + - * / % < <= > >= && || are spelled the same in F#
    };

    /// <summary>
    /// Left-to-right evaluation is made explicit: when both operands may have effects (a call, or a division that
    /// can throw), the left operand is bound to a fresh temporary first. The binding sits inside the parenthesized
    /// expression, so nothing is hoisted out of a conditional branch. &amp;&amp; and || use F#'s own short-circuit operators.
    /// </summary>
    private string EmitBinary(BinaryExpr binary)
    {
        string op = FSharpOperator(binary.Op);
        bool shortCircuit = binary.Op is BinaryOp.And or BinaryOp.Or;
        string? temp = !shortCircuit && MayHaveEffects(binary.Left) && MayHaveEffects(binary.Right) ? NewTemp() : null;
        string left = EmitExpression(binary.Left);
        string right = EmitExpression(binary.Right);
        return temp is null
            ? $"({left} {op} {right})"
            : $"(let {temp} = {left} in ({temp} {op} {right}))";
    }

    /// <summary>Curried call. With two or more effectful arguments, non-atomic arguments are bound to temporaries in source order.</summary>
    private string EmitCall(CallExpr call)
    {
        string callee = call.Symbol!.FSharpName;
        if (call.Arguments.Count == 0)
        {
            return $"({callee} ())";
        }

        if (call.Arguments.Count(MayHaveEffects) < 2)
        {
            return $"({callee} {string.Join(" ", call.Arguments.Select(EmitExpression))})";
        }

        var text = new StringBuilder("(");
        var arguments = new List<string>();
        foreach (var argument in call.Arguments)
        {
            if (IsAtom(argument))
            {
                arguments.Add(EmitExpression(argument));
                continue;
            }

            string temp = NewTemp();
            text.Append($"let {temp} = {EmitExpression(argument)} in ");
            arguments.Add(temp);
        }

        text.Append($"({callee} {string.Join(" ", arguments)}))");
        return text.ToString();
    }

    private static bool IsAtom(Expr expression) => expression is IntLiteralExpr or BoolLiteralExpr or NameExpr;

    /// <summary>True if evaluating the expression could print, recurse, or throw (calls and integer division/remainder).</summary>
    private static bool MayHaveEffects(Expr expression) => expression switch
    {
        CallExpr => true,
        BinaryExpr { Op: BinaryOp.Divide or BinaryOp.Remainder } => true,
        BinaryExpr binary => MayHaveEffects(binary.Left) || MayHaveEffects(binary.Right),
        UnaryExpr unary => MayHaveEffects(unary.Operand),
        ConditionalExpr conditional => MayHaveEffects(conditional.Condition)
                                       || MayHaveEffects(conditional.WhenTrue)
                                       || MayHaveEffects(conditional.WhenFalse),
        _ => false,
    };
}
