<#
.SYNOPSIS
    Builds the Functional C translator, runs the README workflow on examples/sum_squares.fc, runs the
    acceptance tests, and writes TEST-RESULTS.md with the exact commands, exit codes and outputs.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\verify.ps1
#>
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
Set-Location $root
$env:DOTNET_NOLOGO = '1'
$env:DOTNET_CLI_TELEMETRY_OPTOUT = '1'

function Invoke-Native([string]$file, [string[]]$arguments) {
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $file
    $quoted = foreach ($a in $arguments) { if ($a -match '[\s"]') { '"' + ($a -replace '"', '\"') + '"' } else { $a } }
    $psi.Arguments = $quoted -join ' '
    $psi.WorkingDirectory = $root
    $psi.UseShellExecute = $false
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true
    $process = [System.Diagnostics.Process]::Start($psi)
    $stdout = $process.StandardOutput.ReadToEndAsync()
    $stderr = $process.StandardError.ReadToEndAsync()
    $process.WaitForExit()
    [pscustomobject]@{ ExitCode = $process.ExitCode; Stdout = $stdout.Result; Stderr = $stderr.Result }
}

$steps = New-Object System.Collections.Generic.List[object]

function Step([string]$title, [string[]]$arguments, [int]$expectedExit = 0, [scriptblock]$extraCheck = $null) {
    $command = 'dotnet ' + ($arguments -join ' ')
    Write-Host "> $command"
    $r = Invoke-Native 'dotnet' $arguments
    $problems = @()
    if ($r.ExitCode -ne $expectedExit) { $problems += "exit code $($r.ExitCode), expected $expectedExit" }
    if ($extraCheck) { foreach ($p in @(& $extraCheck $r)) { if ($p) { $problems += $p } } }
    $ok = $problems.Count -eq 0
    Write-Host ("  exit {0} -> {1}" -f $r.ExitCode, $(if ($ok) { 'OK' } else { 'FAILED: ' + ($problems -join '; ') }))
    $steps.Add([pscustomobject]@{ Title = $title; Command = $command; Expected = $expectedExit; Result = $r; Ok = $ok; Problems = $problems })
    return $r
}

function Fence([string]$text) {
    $t = $text.TrimEnd()
    if ($t.Length -eq 0) { $t = '(empty)' }
    return "``````text`n$t`n``````"
}

# ---------------------------------------------------------------- environment
$sdkVersion = (Invoke-Native 'dotnet' @('--version')).Stdout.Trim()
$sdkList = (Invoke-Native 'dotnet' @('--list-sdks')).Stdout.Trim()
$targetFramework = ([xml](Get-Content 'src/FunctionalC.Compiler/FunctionalC.Compiler.csproj')).Project.PropertyGroup.TargetFramework | Select-Object -First 1

# ---------------------------------------------------------------- README workflow
Step 'Build the translator' @('build', 'src/FunctionalC.Compiler/FunctionalC.Compiler.csproj') | Out-Null

Step 'Translate the sample' @('run', '--project', 'src/FunctionalC.Compiler', '--', 'examples/sum_squares.fc', '--out', 'generated/SampleApp/Program.fs') | Out-Null

Step 'Build the generated F#' @('build', 'generated/SampleApp/SampleApp.fsproj') | Out-Null

$sample = Step 'Run the generated program' @('run', '--no-build', '--project', 'generated/SampleApp') 0 {
    param($r)
    if ($r.Stdout -ne "55`n") { "stdout was '$($r.Stdout -replace "`r", '\r' -replace "`n", '\n')', expected '55\n'" }
}

$hashBefore = (Get-FileHash 'generated/SampleApp/Program.fs').Hash
Step 'A failing translation must not touch the existing output' @('run', '--project', 'src/FunctionalC.Compiler', '--', 'tests/cases/reject/immutable_reassign.fc', '--out', 'generated/SampleApp/Program.fs') 1 {
    param($r)
    if ((Get-FileHash 'generated/SampleApp/Program.fs').Hash -ne $hashBefore) { 'generated/SampleApp/Program.fs changed' }
} | Out-Null

# ---------------------------------------------------------------- acceptance tests
Step 'Build the test harness' @('build', 'tests/FunctionalC.Tests/FunctionalC.Tests.csproj') | Out-Null
$reportPath = 'tests/work/harness-report.md'
$harness = Step 'Run the acceptance tests' @('run', '--no-build', '--project', 'tests/FunctionalC.Tests', '--', '--report', $reportPath)
$harnessSummary = ($harness.Stdout -split "`n" | Where-Object { $_ -match '^Passed: ' } | Select-Object -Last 1)

# ---------------------------------------------------------------- report
$allOk = -not ($steps | Where-Object { -not $_.Ok })
$sb = New-Object System.Text.StringBuilder
function Add([string]$line = '') { [void]$sb.AppendLine($line) }

Add '# Functional C prototype: test results'
Add
Add 'Generated by `verify.ps1`. Every command, exit code and output below was captured from an actual run. Paths are shown relative to the repository root.'
Add
Add "- Date: $((Get-Date).ToString('yyyy-MM-dd HH:mm:ss zzz'))"
Add "- OS: $([System.Environment]::OSVersion.VersionString)"
Add "- .NET SDK used (``dotnet --version``): **$sdkVersion**"
Add "- Target framework of all projects: **$targetFramework**"
Add "- Installed SDKs (``dotnet --list-sdks``):"
Add
Add (Fence $sdkList)
Add
Add "## Summary"
Add
Add "- Overall: **$(if ($allOk) { 'all steps passed' } else { 'FAILURES - see below' })**"
Add "- Sum-of-squares program: stdout ``$(($sample.Stdout -replace "`r", '\r' -replace "`n", '\n'))``, exit code **$($sample.ExitCode)**"
Add "- Acceptance tests: $harnessSummary"
Add
Add '| # | Step | Command | Exit code (expected) | Result |'
Add '| --- | --- | --- | --- | --- |'
$i = 0
foreach ($s in $steps) {
    $i++
    Add ("| {0} | {1} | ``{2}`` | {3} ({4}) | {5} |" -f $i, $s.Title, $s.Command, $s.Result.ExitCode, $s.Expected, $(if ($s.Ok) { 'OK' } else { 'FAILED: ' + ($s.Problems -join '; ') }))
}

Add
Add '## Workflow commands and outputs'
$i = 0
foreach ($s in $steps) {
    $i++
    Add
    Add "### $i. $($s.Title)"
    Add
    Add "``$($s.Command)`` - exit code **$($s.Result.ExitCode)** (expected $($s.Expected))"
    Add
    if ($s.Title -eq 'Run the acceptance tests') {
        Add 'Console output:'
    } else {
        Add 'Standard output:'
    }
    Add
    Add (Fence $s.Result.Stdout)
    if ($s.Result.Stderr.Trim().Length -gt 0) {
        Add
        Add 'Standard error:'
        Add
        Add (Fence $s.Result.Stderr)
    }
}

Add
Add '## Acceptance test details'
Add
if (Test-Path $reportPath) {
    Add ((Get-Content $reportPath -Raw).TrimEnd())
} else {
    Add "Report file $reportPath was not produced."
}

# The results file is published with the source, so it names no local folders: paths under the repository
# become relative, and the user profile folder becomes '~'.
$report = $sb.ToString().Replace($root + [System.IO.Path]::DirectorySeparatorChar, '').Replace($root, '.')
if ($env:USERPROFILE) { $report = $report.Replace($env:USERPROFILE, '~') }
[System.IO.File]::WriteAllText((Join-Path $root 'TEST-RESULTS.md'), $report, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ''
Write-Host "Wrote $(Join-Path $root 'TEST-RESULTS.md')"
if ($allOk) { Write-Host 'All steps passed.'; exit 0 } else { Write-Host 'Some steps FAILED.'; exit 1 }
